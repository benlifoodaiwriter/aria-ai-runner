#!/usr/bin/env python3
"""
SEOlity i18n build:
  1. extracts t('…') strings from assets/admin/*.js (+ dynamic enum words)
  2. generates src/Admin/I18n.php (JS dictionary passed through __())
  3. extracts PHP gettext strings
  4. writes languages/seolity.pot and languages/seolity-fa_IR.po from tools/i18n/fa-*.tsv
  5. compiles languages/seolity-fa_IR.mo

Run from the plugin root:  python3 tools/i18n/build.py
"""
import glob, json, os, re, struct, subprocess, sys, datetime

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
os.chdir(ROOT)

DYNAMIC = ['manual', 'semi', 'autonomous', 'auto', 'on', 'off', 'fa', 'en', 'ar', 'tr', 'de', 'fr', 'es', 'low', 'medium', 'high', 'xhigh', 'max',
           'daily', 'weekly', 'monthly', 'none', 'Organization', 'LocalBusiness', 'Person', 'OnlineStore', 'pending', 'applied', 'applied_editor',
           'rejected', 'reverted', 'superseded', 'running', 'evaluated', 'cancelled', 'done', 'failed', 'open', 'ignored', 'fixed', 'redirected',
           'planned', 'in_progress', 'published', 'skipped', 'ai', 'rule', 'revert', 'restore', 'recommendation', 'internal_link', 'import',
           'slug_change', '404_monitor', 'informational', 'commercial', 'transactional', 'navigational', 'head', 'long_tail', 'question', 'semantic',
           'entity', 'positive', 'negative', 'neutral', 'inconclusive', 'post', 'term', 'user', 'attachment', 'site', 'publish', 'draft', 'future',
           'crawling', 'seeding', 'analyzing', 'missing_topic', 'missing_page', 'weak_page', 'noindex', 'redirect', 'canonicalized', 'error_404',
           'error_410', 'error_500', 'Indexation', 'Meta', 'Content', 'Links', 'Images', 'Schema', 'Performance', 'Security', 'Mobile',
           'International', 'Technical', 'Gsc', 'Keywords', 'Competitors', 'Critical', 'High', 'Medium', 'Low', 'Info', 'instock', 'outofstock', 'onbackorder']


def js_strings():
    out, seen = [], set()
    pat = re.compile(r"""\bt\(\s*(['"])((?:\\.|(?!\1).)*)\1""")
    for f in sorted(glob.glob('assets/admin/*.js')):
        for m in pat.finditer(open(f, encoding='utf8').read()):
            s = m.group(2).replace("\\'", "'").replace('\\"', '"')
            if s not in seen:
                seen.add(s); out.append(s)
    ui = open('assets/admin/ui.js', encoding='utf8').read()
    block = ui[ui.index('var FIELD_LABELS'):ui.index('SL.fieldLabel')]
    for m in re.finditer(r"\w+:\s*'([A-Za-z][^']+)'", block):
        if m.group(1) not in seen:
            seen.add(m.group(1)); out.append(m.group(1))
    adm = open('assets/admin/pages-admin.js', encoding='utf8').read()
    block = adm[adm.index('var LABELS'):adm.index('App.pages.settings')]
    for m in re.finditer(r"'([^']{3,})'", block):
        s = m.group(1)
        if re.match(r'^[a-z_0-9]+$', s) or not re.search(r'[A-Za-z]', s):
            continue
        if s not in seen:
            seen.add(s); out.append(s)
    for s in DYNAMIC:
        if s not in seen:
            seen.add(s); out.append(s)
    return out


def php_strings():
    out, seen = [], set()
    pat = re.compile(r"""\b(?:__|esc_html__|esc_attr__|_e|esc_html_e|esc_attr_e)\(\s*'((?:\\.|[^'\\])*)'\s*,\s*'seolity'""")
    npat = re.compile(r"""\b_n\(\s*'((?:\\.|[^'\\])*)'\s*,\s*'((?:\\.|[^'\\])*)'""")
    plurals = []
    for f in sorted(glob.glob('src/**/*.php', recursive=True)) + ['seolity.php']:
        if f.endswith('Admin/I18n.php'):
            continue
        src = open(f, encoding='utf8').read()
        for m in pat.finditer(src):
            s = m.group(1).replace("\\'", "'")
            if s not in seen:
                seen.add(s); out.append(s)
        for m in npat.finditer(src):
            plurals.append((m.group(1).replace("\\'", "'"), m.group(2).replace("\\'", "'")))
    return out, plurals


def php_quote(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write_i18n_php(strings):
    lines = ['<?php', '/**', ' * GENERATED by tools/i18n/build.py — do not edit by hand.', ' * Translatable UI strings for the admin JavaScript app.', ' *', ' * @package SEOlity', ' */', '',
             'namespace SEOlity\\Admin;', '', "defined( 'ABSPATH' ) || exit;", '', 'final class I18n {', '',
             '\t/** @return array<string,string> English source => translated. */', '\tpublic static function strings() {', '\t\treturn array(']
    for s in strings:
        lines.append('\t\t\t%s => __( %s, \'seolity\' ),' % (php_quote(s), php_quote(s)))
    lines += ['\t\t);', '\t}', '}', '']
    open('src/Admin/I18n.php', 'w', encoding='utf8').write('\n'.join(lines))


def po_escape(s):
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')


def translations():
    tr = {}
    for f in sorted(glob.glob('tools/i18n/fa-*.tsv')):
        for line in open(f, encoding='utf8'):
            if '\t' in line:
                a, b = line.rstrip('\n').split('\t', 1)
                tr[a] = b
    return tr


def write_po(path, entries, plurals, tr, lang):
    now = datetime.datetime.utcnow().strftime('%Y-%m-%d %H:%M+0000')
    head = ['msgid ""', 'msgstr ""', '"Project-Id-Version: SEOlity 1.0.0\\n"', '"POT-Creation-Date: %s\\n"' % now, '"MIME-Version: 1.0\\n"',
            '"Content-Type: text/plain; charset=UTF-8\\n"', '"Content-Transfer-Encoding: 8bit\\n"', '"X-Domain: seolity\\n"']
    if lang:
        head += ['"Language: %s\\n"' % lang, '"Plural-Forms: nplurals=1; plural=0;\\n"']
    else:
        head += ['"Plural-Forms: nplurals=2; plural=(n != 1);\\n"']
    body = ['\n'.join(head), '']
    for s in entries:
        if '%' in s:
            body.append('#, php-format')
        body.append('msgid "%s"' % po_escape(s))
        body.append('msgstr "%s"' % (po_escape(tr.get(s, '')) if lang else ''))
        body.append('')
    for one, many in plurals:
        body.append('#, php-format')
        body.append('msgid "%s"' % po_escape(one))
        body.append('msgid_plural "%s"' % po_escape(many))
        if lang:
            body.append('msgstr[0] "%s"' % po_escape(tr.get(many, tr.get(one, ''))))
        else:
            body.append('msgstr[0] ""')
            body.append('msgstr[1] ""')
        body.append('')
    open(path, 'w', encoding='utf8').write('\n'.join(body))


def write_mo(path, entries, plurals, tr, lang):
    """GNU .mo writer (little endian)."""
    msgs = {'': 'Content-Type: text/plain; charset=UTF-8\nLanguage: %s\nPlural-Forms: nplurals=1; plural=0;\n' % lang}
    for s in entries:
        if tr.get(s):
            msgs[s] = tr[s]
    for one, many in plurals:
        t = tr.get(many, tr.get(one))
        if t:
            msgs[one + '\x00' + many] = t
    keys = sorted(msgs.keys())
    ids = b''
    strs = b''
    offsets = []
    for k in keys:
        kb = k.encode('utf8')
        vb = msgs[k].encode('utf8')
        offsets.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b'\x00'
        strs += vb + b'\x00'
    n = len(keys)
    keystart = 7 * 4 + 16 * n
    valuestart = keystart + len(ids)
    koffsets, voffsets = [], []
    for o1, l1, o2, l2 in offsets:
        koffsets += [l1, o1 + keystart]
        voffsets += [l2, o2 + valuestart]
    out = struct.pack('Iiiiiii', 0x950412de, 0, n, 7 * 4, 7 * 4 + n * 8, 0, 0)
    out += struct.pack('%di' % len(koffsets), *koffsets)
    out += struct.pack('%di' % len(voffsets), *voffsets)
    out += ids + strs
    open(path, 'wb').write(out)
    return len(msgs) - 1


def main():
    js = js_strings()
    write_i18n_php(js)
    php, plurals = php_strings()
    allstrings = list(dict.fromkeys(php + js))
    tr = translations()
    os.makedirs('languages', exist_ok=True)
    write_po('languages/seolity.pot', allstrings, plurals, {}, None)
    write_po('languages/seolity-fa_IR.po', allstrings, plurals, tr, 'fa_IR')
    n = write_mo('languages/seolity-fa_IR.mo', allstrings, plurals, tr, 'fa_IR')
    missing = [s for s in allstrings if s not in tr]
    print('strings: %d (php %d, js %d) · fa_IR translated: %d · missing: %d' % (len(allstrings), len(php), len(js), n, len(missing)))
    if missing:
        print('missing sample:', missing[:15])
        open(os.environ.get('SEOLITY_I18N_MISSING', os.devnull), 'w', encoding='utf8').write('\n'.join(missing))


if __name__ == '__main__':
    main()
