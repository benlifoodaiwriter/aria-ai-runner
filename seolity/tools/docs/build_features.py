#!/usr/bin/env python3
"""Build docs/FEATURES.md from the feature catalog in features_data.py.

Each category declares defaults (dependencies, UI location, automation, risk, DB, API, edition);
each feature line is "Name | Purpose | User value | Input | Output [| key=value; key=value]".
Override keys: deps, ui, auto, risk, db, api, ed.

Editions: "1.0" = implemented in this release; "Pro" / "Ent" = roadmap (not implemented yet).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from features_data import CATEGORIES  # noqa: E402

ED = {'1.0': '✅ 1.0', 'Pro': '🗺 Pro', 'Ent': '🗺 Enterprise'}
KEYS = ('deps', 'ui', 'auto', 'risk', 'db', 'api', 'ed')


def parse(cat):
    out = []
    for raw in cat['features'].strip().splitlines():
        raw = raw.strip()
        if not raw or raw.startswith('#'):
            continue
        parts = [p.strip() for p in raw.split(' | ')]
        if len(parts) not in (5, 6):
            raise SystemExit(f"Bad feature line in {cat['name']}: {raw}")
        f = dict(zip(('name', 'purpose', 'value', 'input', 'output'), parts[:5]))
        for k in KEYS:
            f[k] = cat[k]
        if len(parts) == 6:
            for kv in parts[5].split(';'):
                if not kv.strip():
                    continue
                k, v = kv.split('=', 1)
                k = k.strip()
                if k not in KEYS:
                    raise SystemExit(f"Unknown key {k} in {raw}")
                f[k] = v.strip()
        out.append(f)
    return out


def cell(s):
    return s.replace('|', '\\|')


def main():
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    cats = [(c, parse(c)) for c in CATEGORIES]
    total = sum(len(f) for _, f in cats)
    done = sum(1 for _, fs in cats for f in fs if f['ed'] == '1.0')
    lines = [
        '# SEOlity — Feature Catalog',
        '',
        f'**{total} features** in {len(cats)} categories. **{done}** are implemented in this release (✅ 1.0); '
        f'the remaining {total - done} are the documented Pro/Enterprise roadmap (🗺) and are *not* implemented yet.',
        '',
        'Columns: **Purpose** (what it does) · **User value** · **Input** · **Output** · **Dependencies** · '
        '**UI location** · **Automation** (Manual = user-triggered; Assisted = AI proposes, human approves; '
        'Semi = auto-applies low-risk changes in Semi/Autonomous mode; Auto = runs in the background; '
        'Scheduled = cron pipeline) · **Risk** (None = read-only; Low/Medium/High = level of the change it can make, '
        'which decides approval) · **DB** (tables, all prefixed `seolity_`) · **API** (REST routes under '
        '`/wp-json/seolity/v1`, or external APIs) · **Edition**.',
        '',
        'Generated by `tools/docs/build_features.py` from `tools/docs/features_data.py`.',
        '',
        '## Categories',
        '',
    ]
    n = 0
    for c, fs in cats:
        anchor = re.sub(r'[^\w\- ]', '', c['name'].lower()).replace(' ', '-')  # GitHub heading slug
        lines.append(f"- [{c['name']}](#{anchor}) — {len(fs)} features")
    lines.append('')
    for c, fs in cats:
        lines += [f"## {c['name']}", '', c.get('intro', ''), '',
                  '| # | Feature | Purpose | User value | Input | Output | Dependencies | UI location | Automation | Risk | DB | API | Edition |',
                  '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
        for f in fs:
            n += 1
            lines.append('| ' + ' | '.join([str(n)] + [cell(f[k]) for k in ('name', 'purpose', 'value', 'input', 'output', 'deps', 'ui', 'auto', 'risk', 'db', 'api')] + [ED.get(f['ed'], f['ed'])]) + ' |')
        lines.append('')
    path = os.path.join(root, 'docs', 'FEATURES.md')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'{path}: {total} features ({done} implemented)')


if __name__ == '__main__':
    main()
