#!/usr/bin/env node
/**
 * Build docs/CONNECT.md (Persian + English) from the in-app connection guide
 * data in assets/admin/pages-guide.js, so both always say the same thing.
 * Run from the plugin root:  node tools/docs/build_connect.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve( path.dirname( new URL( import.meta.url ).pathname ), '..', '..' );
const src = fs.readFileSync( path.join( root, 'assets/admin/pages-guide.js' ), 'utf8' );
const App = { pages: {} };
const SL = { app: App, config: { rtl: false }, t: ( s ) => s, h: () => null };
vm.runInNewContext( src, { window: { SL }, document: {} } );
const { services, groups } = App.guideData;

function render( lang ) {
	const L = ( x ) => ( x && typeof x === 'object' ? x[ lang ] : x );
	const out = [];
	for ( const [ id, label ] of groups ) {
		out.push( `### ${ L( label ) }`, '' );
		for ( const s of services.filter( ( x ) => x.group === id ) ) {
			out.push( `#### ${ L( s.title ) }`, '' );
			out.push( s.badges.map( ( b ) => '`' + L( b[ 0 ] ) + '`' ).join( ' ' ), '' );
			out.push( L( s.why ), '' );
			if ( s.need?.length ) {
				out.push( `**${ lang === 'fa' ? 'پیش‌نیازها' : 'You need' }:** ` + s.need.map( L ).join( lang === 'fa' ? '؛ ' : '; ' ), '' );
			}
			s.steps.forEach( ( st, i ) => {
				let line = `${ i + 1 }. ${ L( st.text ) }`;
				if ( st.links ) {
					line += ' ' + st.links.map( ( l ) => `[${ L( l[ 0 ] ) }](${ l[ 1 ] })` ).join( ' · ' );
				}
				out.push( line );
				if ( st.code ) {
					out.push( '', '   ```', '   ' + st.code, '   ```' );
				}
				if ( st.redirect ) {
					out.push( '', '   ```', '   https://YOUR-SITE/wp-admin/admin-post.php', '   ```' );
				}
			} );
			out.push( '' );
			if ( s.trouble?.length ) {
				out.push( `**${ lang === 'fa' ? 'رفع مشکل' : 'Troubleshooting' }**`, '' );
				s.trouble.forEach( ( x ) => out.push( `- **${ L( x[ 0 ] ) }** — ${ L( x[ 1 ] ) }` ) );
				out.push( '' );
			}
			if ( s.docs?.length ) {
				out.push( `**${ lang === 'fa' ? 'مستندات رسمی' : 'Official docs' }:** ` + s.docs.map( ( l ) => `[${ L( l[ 0 ] ) }](${ l[ 1 ] })` ).join( ' · ' ), '' );
			}
		}
	}
	return out.join( '\n' );
}

const md = [
	'# SEOlity — Connection guide / راهنمای اتصال',
	'',
	'Generated by `tools/docs/build_connect.mjs` from `assets/admin/pages-guide.js` (the same guide is inside the plugin: **SEOlity → Connection guide**).',
	'',
	'- [فارسی](#فارسی)',
	'- [English](#english)',
	'',
	'## فارسی',
	'',
	'<div dir="rtl">',
	'',
	render( 'fa' ),
	'',
	'</div>',
	'',
	'## English',
	'',
	render( 'en' ),
	'',
].join( '\n' );
fs.writeFileSync( path.join( root, 'docs/CONNECT.md' ), md );
console.log( `docs/CONNECT.md: ${ services.length } services` );
